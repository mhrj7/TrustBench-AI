#!/usr/bin/env python3
"""TB-054 acceptance check: every Core task in the planning workbook has acceptance evidence on disk or remains open,
and the handover (docs/handover.md) records both.

The Core-task table in the handover is generated from the workbook between two markers; `--write` regenerates it. The
check fails when a Completed Core task lists no evidence or a path missing on disk, when the generated table in the
handover differs from the workbook, or when a required handover section is missing. The result is written to
evidence/tb054-handover-check.json.
"""
import argparse
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

import openpyxl

ROOT = Path(__file__).resolve().parents[1]
WORKBOOK = ROOT / "planning" / "TrustBench-AI_Plan.xlsx"
HANDOVER = ROOT / "docs" / "handover.md"
OUT = ROOT / "evidence" / "tb054-handover-check.json"
BEGIN, END = "<!-- core-tasks:begin (generated by scripts/check-handover.py --write) -->", "<!-- core-tasks:end -->"
SECTIONS = ["## Where the project stands", "## Core tasks: evidence or open", "## Unresolved failure modes",
            "## Supported versions", "## Next experiment", "## Maintenance triggers", "## Backlog"]
COL = {"id": 0, "task": 2, "status": 3, "acceptance": 13, "scope": 16, "evidence": 18, "next": 19}


def resolve(path: str) -> Path:
    """Same rule as scripts/check-workbook.py: repository-relative, or an absolute path of the original checkout."""
    marker = f"/{ROOT.name}/"
    if path.startswith("/") and marker in path:
        return ROOT / path.split(marker, 1)[1]
    return Path(path) if path.startswith("/") else ROOT / path


def core_tasks() -> list[dict]:
    ws = openpyxl.load_workbook(WORKBOOK, read_only=True, data_only=True).worksheets[0]
    rows = []
    for r in ws.iter_rows(values_only=True):
        if not (r and isinstance(r[0], str) and r[0].startswith("TB-") and r[0][3:].isdigit()) or r[COL["scope"]] != "Core":
            continue
        evidence = [p.strip() for p in str(r[COL["evidence"]] or "").split(";") if p.strip()]
        missing = [p for p in evidence if not resolve(p).exists()]
        rows.append({"id": r[0], "task": r[COL["task"]], "status": r[COL["status"]], "evidence": evidence,
                     "missing": missing, "next": r[COL["next"]] or ""})
    return rows


def table(rows: list[dict]) -> str:
    def cell(s: str) -> str:
        return str(s).replace("|", "\\|").replace("\n", " ")
    lines = ["| Task | Deliverable | Status | Evidence on disk |", "| --- | --- | --- | --- |"]
    for t in rows:
        if t["status"] == "Completed":
            ev = f"`{t['evidence'][0]}`" + (f" and {len(t['evidence']) - 1} more" if len(t["evidence"]) > 1 else "") if t["evidence"] else "none"
            ok = "missing: " + ", ".join(t["missing"]) if t["missing"] else ev
        else:
            ok = "open: " + cell(t["next"] or "not started")
        lines.append(f"| {t['id']} | {cell(t['task'])} | {t['status']} | {ok} |")
    done = sum(t["status"] == "Completed" for t in rows)
    lines.append("")
    lines.append(f"{done} of {len(rows)} Core tasks Completed with evidence on disk; {len(rows) - done} open.")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true", help="regenerate the Core-task table in docs/handover.md")
    args = ap.parse_args()
    rows = core_tasks()
    doc = HANDOVER.read_text() if HANDOVER.exists() else ""
    generated = f"{BEGIN}\n{table(rows)}\n{END}"
    if args.write and BEGIN in doc and END in doc:
        doc = doc[: doc.index(BEGIN)] + generated + doc[doc.index(END) + len(END):]
        HANDOVER.write_text(doc)
    problems = []
    for t in rows:
        if t["status"] == "Completed" and not t["evidence"]:
            problems.append(f"{t['id']}: Completed without evidence")
        for p in t["missing"]:
            if t["status"] == "Completed":
                problems.append(f"{t['id']}: evidence missing on disk: {p}")
    for s in SECTIONS:
        if s not in doc:
            problems.append(f"handover: missing section {s!r}")
    if generated not in doc:
        problems.append("handover: the Core-task table differs from the workbook (run with --write)")
    result = {
        "task_id": "TB-054", "checked_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "workbook": str(WORKBOOK.relative_to(ROOT)), "handover": str(HANDOVER.relative_to(ROOT)),
        "core_tasks": len(rows), "completed_with_evidence": sum(t["status"] == "Completed" and t["evidence"] and not t["missing"] for t in rows),
        "open": [{"id": t["id"], "status": t["status"], "next": t["next"]} for t in rows if t["status"] != "Completed"],
        "problems": problems, "ok": not problems,
    }
    OUT.write_text(json.dumps(result, indent=1) + "\n")
    print(f"{len(rows)} Core tasks; {result['completed_with_evidence']} Completed with evidence; {len(result['open'])} open; {len(problems)} problem(s)")
    for p in problems:
        print("  -", p)
    return 0 if not problems else 1


if __name__ == "__main__":
    sys.exit(main())
