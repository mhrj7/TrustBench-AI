#!/usr/bin/env python3
"""TB-046: the reproducibility package (configs/repro.yaml).

  repro.py build       write repro/manifest.json (published fixture IDs by split, seeds, config / script / raw-record hashes,
                       exclusions) and repro/README.md (the documented steps)
  repro.py check       the published tree holds no excluded path, secret or personal identifier, and every hash in
                       repro/manifest.json matches the files
  repro.py reproduce   run every offline step, then compare every tracked file the steps rewrote with the committed version,
                       ignoring only the declared volatile fields; writes repro/reproduction-log.json; exit 0 only if all
                       steps pass and nothing else changed

Run inside a git checkout (a clone of the release tag). No step needs a key, a model or the network."""
import glob, hashlib, json, platform, re, subprocess, sys, time
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CFG = json.loads((ROOT / 'configs/repro.yaml').read_text())
INV = CFG['inventory']
OUT = ROOT / 'repro'


def git(*args) -> str:
    return subprocess.run(['git', *args], cwd=ROOT, capture_output=True, text=True, check=True).stdout


def tracked() -> list[str]:
    return git('ls-files', '-z').split('\0')[:-1]


def sha(path: str) -> str:
    return hashlib.sha256((ROOT / path).read_bytes()).hexdigest()


def expand(patterns: list[str]) -> list[str]:
    files, out = set(tracked()), set()
    for pat in patterns:
        hit = {p for p in glob.glob(pat, root_dir=ROOT, recursive=True) if p in files}
        if not hit:
            sys.exit(f'inventory pattern matches no tracked file: {pat}')
        out |= hit
    return sorted(out)


def seeds() -> dict:
    reg = json.loads((ROOT / INV['seeds_from']).read_text())
    out = {}
    for key in CFG['inventory']['seed_keys']:
        v = reg
        for part in key.split('.'):
            v = v[part]
        out[key] = v
    return out


def fixtures() -> dict:
    splits = json.loads((ROOT / 'data/splits.json').read_text())
    by = {}
    for g in splits['groups']:
        by.setdefault(g['split'], []).extend(g['fixture_ids'])
    out = {k: sorted(v) for k, v in sorted(by.items())}
    out['holdout2'] = sorted(splits['holdout2_manifest']['fixture_ids'])
    return {'split_id': splits['split_id'], 'by_split': out, 'counts': {k: len(v) for k, v in out.items()},
            'sealed_manifest_sha256': {'holdout': splits['holdout_manifest']['sha256'], 'holdout2': splits['holdout2_manifest']['sha256']},
            'note': 'Every fixture is synthetic. The holdouts were run once each (TB-032) and are published for inspection and re-analysis; '
                    'the CLI refuses to rerun them.'}


def manifest() -> dict:
    return {'task_id': 'TB-046', 'fixtures': fixtures(), 'seeds': seeds(),
            'files': {kind: {p: sha(p) for p in expand(INV[kind])} for kind in ('fixtures', 'configs', 'analysis_scripts', 'raw_records')},
            'exclusions': CFG['exclusions'], 'offline_steps': [s['name'] + ': ' + ' '.join(s['command']) for s in CFG['offline_steps']]}


def build():
    OUT.mkdir(exist_ok=True)
    m = manifest()
    (OUT / 'manifest.json').write_text(json.dumps(m, indent=1) + '\n')
    (OUT / 'README.md').write_text(readme(m))
    print(json.dumps({'fixtures': m['fixtures']['counts'], **{k: len(v) for k, v in m['files'].items()}}))


def readme(m: dict) -> str:
    steps = '\n'.join(f"{i}. {s['name']}: `{' '.join(s['command'])}`" for i, s in enumerate(CFG['offline_steps'], 1))
    excl = '\n'.join(f"- `{x['path']}`: {x['reason']}" for x in CFG['exclusions'])
    counts = ', '.join(f'{k} {v}' for k, v in m['fixtures']['counts'].items())
    seeds_ = ', '.join(f'`{k}` = {v}' for k, v in m['seeds'].items())
    log = json.loads((ROOT / CFG['reproduction_log']).read_text()) if (ROOT / CFG['reproduction_log']).exists() else None
    result = ('Not yet reproduced.' if not log else
              f"Last reproduction ({log['finished_at'][:10]}, commit `{log['commit'][:7]}`, {log['environment']}): "
              f"{sum(s['exit_code'] == 0 for s in log['steps'])}/{len(log['steps'])} steps passed, "
              f"{len(log['unexpected_changes'])} unexpected file changes, outcome **{log['outcome']}**.")
    return f"""# Reproducing TrustBench offline (TB-046)

This package lets someone else rerun the credential-free part of TrustBench from a clean clone and check that they get the
published results. Generated by `scripts/repro.py build` from `configs/repro.yaml`; do not edit by hand.

## What is published

[`manifest.json`](manifest.json) lists, with SHA-256 hashes:

- **Fixture IDs by split** ({counts}; split `{m['fixtures']['split_id']}`). All fixtures are synthetic; the two holdouts were
  each run once and are published for re-analysis, not for rerunning.
- **Seeds:** {seeds_}.
- **Configs** ({len(m['files']['configs'])} files), **analysis scripts** ({len(m['files']['analysis_scripts'])}),
  **fixtures** ({len(m['files']['fixtures'])}) and the **raw run records** the results are computed from ({len(m['files']['raw_records'])}).

Not published (`sh bin/trustbench` never needs them for the offline subset):

{excl}

`scripts/repro.py check` fails if any of these is tracked, if a tracked file contains a credential-shaped string or a personal
identifier, or if a hash in `manifest.json` no longer matches.

## Steps

Requirements: git, Node.js 26.5.0 with npm 12.0.0, and [uv](https://docs.astral.sh/uv/) (it installs Python 3.14.0). Or only
Docker, with the container route below. No API key, model or network access is needed after installation.

```bash
git clone --branch <release tag> https://github.com/mhrj7/TrustBench-AI.git
```

```bash
cd TrustBench-AI && export TRUSTBENCH_STORAGE_ROOT="$(dirname "$PWD")" npm_config_cache="$(dirname "$PWD")/.cache/npm"
```

```bash
cp .env.example .env && npm ci && sh scripts/setup-python.sh
```

```bash
.venv-tools/bin/python scripts/repro.py check && .venv-tools/bin/python scripts/repro.py reproduce
```

`reproduce` runs these steps in order:

{steps}

It then compares every tracked file the steps rewrote with the committed version. Only timestamps and per-run IDs
(`{'`, `'.join(CFG['volatile_json_keys'])}`, and the date line of the label-audit report) may differ. Any other difference, or any failed
step, fails the reproduction. The result is written to `{CFG['reproduction_log']}`.

Container route (a clean environment as a non-root user, from the files git tracks at a commit):

```bash
sh repro/run-in-container.sh <commit or tag>
```

## Result

{result}

## What this does not reproduce

- **Live model runs.** The holdout results came from a hosted free model sampled at temperature 0.3. Providers change and
  retire models, and sampling varies, so a historical run cannot be replayed exactly. The package republishes the raw records
  of those runs, and every published number is recomputed from them. A new live run (`sh bin/trustbench benchmark dev-frozen`)
  needs your own free-tier key and gives new samples, not the same ones.
- **The AgentDojo-derived check** (`npm run verify:data`) needs the pinned AgentDojo checkout: `sh bin/trustbench fetch-data`
  clones it over the network.
- **The review website's browser tests** need Google Chrome; the full `npm run verify` runs them.
"""


def check():
    files = tracked()
    problems = []
    for x in CFG['exclusions']:
        hit = [f for f in files if f == x['path'] or f.startswith(x['path'].rstrip('/') + '/')]
        if hit:
            problems.append(f"excluded path is tracked: {x['path']} ({len(hit)} files)")
    patterns = [(re.compile(p), 'secret') for p in CFG['secret_patterns']] + [(re.compile(p), 'personal identifier') for p in CFG['personal_patterns']]
    for f in files:
        if f in CFG['secret_allowlist'] or f.endswith(('package-lock.json', '.xlsx', '.jpg', '.png', '.sqlite', '.pdf', '.woff2')):
            continue
        try:
            text = (ROOT / f).read_text(errors='strict')
        except (UnicodeDecodeError, IsADirectoryError, FileNotFoundError):
            continue
        for rx, kind in patterns:
            if rx.search(text):
                problems.append(f'{kind} pattern {rx.pattern!r} in {f}')
    m = json.loads((OUT / 'manifest.json').read_text())
    for kind, entries in m['files'].items():
        for p, h in entries.items():
            if not (ROOT / p).exists() or sha(p) != h:
                problems.append(f'{kind} hash mismatch: {p}')
    if manifest() != m:
        problems.append('repro/manifest.json is out of date: run scripts/repro.py build')
    print(json.dumps({'ok': not problems, 'tracked_files': len(files), 'problems': problems}, indent=1))
    sys.exit(0 if not problems else 1)


def strip(path: str, text: str):
    if path.endswith('.json'):
        try:
            return drop(json.loads(text))
        except json.JSONDecodeError:
            pass
    lines = text.splitlines()
    return [l for l in lines if not any(re.search(p, l) for p in CFG['volatile_line_patterns'])]


def drop(v):
    if isinstance(v, dict):
        return {k: drop(x) for k, x in v.items() if k not in CFG['volatile_json_keys']}
    if isinstance(v, list):
        return [drop(x) for x in v]
    return v


def reproduce():
    if git('status', '--porcelain', '--untracked-files=no').strip():
        sys.exit('reproduce needs a clean checkout: tracked files are already modified')
    started, steps = datetime.now(timezone.utc).isoformat(timespec='seconds'), []
    for s in CFG['offline_steps']:
        t = time.monotonic()
        p = subprocess.run(s['command'], cwd=ROOT, capture_output=True, text=True)
        steps.append({'name': s['name'], 'command': ' '.join(s['command']), 'exit_code': p.returncode, 'seconds': round(time.monotonic() - t, 1),
                      'tail': (p.stdout + p.stderr).strip().splitlines()[-3:]})
        print(f"{'ok ' if p.returncode == 0 else 'FAIL'} {s['name']} ({steps[-1]['seconds']} s)", flush=True)
    changed = [l[3:] for l in git('status', '--porcelain', '--untracked-files=no').splitlines()]
    volatile_only, unexpected = [], []
    for f in changed:
        committed = git('show', f'HEAD:{f}') if f.endswith(('.json', '.md', '.csv', '.jsonl', '.txt', '.xml')) else None
        same = committed is not None and (ROOT / f).exists() and strip(f, committed) == strip(f, (ROOT / f).read_text())
        (volatile_only if same else unexpected).append(f)
    log = {'task_id': 'TB-046', 'commit': git('rev-parse', 'HEAD').strip(), 'started_at': started, 'finished_at': datetime.now(timezone.utc).isoformat(timespec='seconds'),
           'environment': f"{platform.system()} {platform.machine()}, Python {platform.python_version()}, "
                          f"Node {subprocess.run(['node', '--version'], capture_output=True, text=True).stdout.strip()}",
           'steps': steps, 'rewritten_files_volatile_only': volatile_only, 'unexpected_changes': unexpected,
           'outcome': 'REPRODUCED' if all(s['exit_code'] == 0 for s in steps) and not unexpected else 'NOT REPRODUCED'}
    subprocess.run(['git', 'checkout', '--', *volatile_only], cwd=ROOT, check=True) if volatile_only else None  # leave the checkout as cloned
    (ROOT / CFG['reproduction_log']).write_text(json.dumps(log, indent=1) + '\n')
    print(json.dumps({'outcome': log['outcome'], 'steps_passed': sum(s['exit_code'] == 0 for s in steps), 'steps': len(steps),
                      'volatile_only': len(volatile_only), 'unexpected': unexpected}))
    sys.exit(0 if log['outcome'] == 'REPRODUCED' else 1)


if __name__ == '__main__':
    {'build': build, 'check': check, 'reproduce': reproduce}.get(sys.argv[1] if len(sys.argv) > 1 else '', lambda: sys.exit(__doc__))()
