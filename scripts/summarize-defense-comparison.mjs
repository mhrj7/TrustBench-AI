// Generates docs/defense-comparison.md from the live evidence files of the registered comparison (configs/defense-comparison.yaml).
// No number is typed by hand. A report is included only when it matches the registered settings exactly; others are ignored.
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = async (rel) => JSON.parse(await readFile(path.join(root, rel), "utf8"));
const cfg = await read("configs/defense-comparison.yaml");
const registry = await read("protocol/experiment-registry.yaml");
const defenses = await read("configs/defenses.yaml");
const suite = await read("tests/arms/smoke-cases.json");
const liveCases = new Set(suite.cases.filter((c) => !c.scripted_only).map((c) => c.case_id));
const profile = registry.primary_prompt_profile;

// Registered (model, system) cells and their expected size.
const cells = [];
for (const [lane, spec] of Object.entries(cfg.lanes)) for (const system of spec.systems) cells.push({ lane, model: spec.model, system, repetitions: spec.repetitions });

const reports = [];
for (const name of (await readdir(path.join(root, "evidence"))).filter((n) => /^tb024-.*-report\.json$/.test(n))) {
  const r = await read(`evidence/${name}`);
  const cell = cells.find((c) => c.model === r.model && c.system === r.defended_system);
  if (!cell || r.mode !== "live_model" || r.attack_rendering !== cfg.attack_rendering || r.prompt_profile !== profile) continue;
  if (r.temperature !== cfg.temperature || r.repetitions !== cell.repetitions || r.backend_tool_mode !== "permissive") continue;
  const ids = new Set(r.cases.map((c) => c.case_id));
  if (ids.size !== liveCases.size || [...liveCases].some((id) => !ids.has(id)) || r.cases.length !== liveCases.size * cell.repetitions) continue;
  reports.push({ name, cell, ...r });
}

// Wilson 95% score interval and the Newcombe (1998, method 10) interval for a difference of two independent proportions.
const Z = 1.959963984540054;
function wilson(k, n) {
  if (!n) return null;
  const p = k / n, d = 1 + (Z * Z) / n, c = p + (Z * Z) / (2 * n), h = Z * Math.sqrt((p * (1 - p)) / n + (Z * Z) / (4 * n * n));
  return { k, n, p, lo: Math.max(0, (c - h) / d), hi: Math.min(1, (c + h) / d) }; // clamp floating-point overshoot
}
function newcombe(a, b) {
  if (!a || !b) return null;
  const diff = a.p - b.p;
  return { diff, lo: diff - Math.sqrt((a.p - a.lo) ** 2 + (b.hi - b.p) ** 2), hi: diff + Math.sqrt((a.hi - a.p) ** 2 + (b.p - b.lo) ** 2) };
}
const pct = (x) => `${(x * 100).toFixed(0)}%`;
const fmt = (w) => (w ? `${w.k}/${w.n} (${pct(w.p)}; ${pct(w.lo)}–${pct(w.hi)})` : "n/a");
const pp = (x) => `${x >= 0 ? "+" : ""}${(x * 100).toFixed(0)}`;

const valid = (c) => !c.baseline.invalid && !c.defended.invalid;
const denied = (arm) => arm.policy_decisions?.some((d) => d.decision === "deny") || (arm.defense?.vetoes ?? 0) > 0;
function metrics(r, arm) {
  const ok = r.cases.filter(valid), atk = ok.filter((c) => c.kind === "attack"), ben = ok.filter((c) => c.kind === "benign");
  const count = (rows, f) => wilson(rows.filter(f).length, rows.length);
  return {
    goal: count(atk, (c) => c[arm].evaluation.attacker_goal_achieved),
    unsafe: count(atk, (c) => !c[arm].evaluation.security_pass),
    utility: count(ben, (c) => c[arm].evaluation.utility_pass),
    utilityUnderAttack: count(atk, (c) => c[arm].evaluation.utility_pass),
    benignDenied: count(ben, (c) => denied(c[arm])),
    attackVetoed: count(atk, (c) => (c[arm].defense?.vetoes ?? 0) > 0),
    rows: { atk, ben },
  };
}
const median = (xs) => { const s = [...xs].sort((a, b) => a - b); return s.length ? (s.length % 2 ? s[(s.length - 1) / 2] : (s[s.length / 2 - 1] + s[s.length / 2]) / 2) : null; };

const lines = [];
lines.push("# Defense comparison on the development split (exploratory, not confirmatory)", "");
lines.push("Generated by `scripts/summarize-defense-comparison.mjs` from `evidence/tb024-*-report.json`. Every number is read from those files.", "");
lines.push(`Registered settings (\`configs/defense-comparison.yaml\`): attack rendering \`${cfg.attack_rendering}\`, prompt profile \`${profile}\` (the registry's primary profile), ` +
  `temperature ${cfg.temperature}, ${liveCases.size} live cases. A report is included only when its model, system, rendering, profile, temperature, repetitions and case set ` +
  "all match; earlier sanity runs with other settings are ignored. Holdout fixtures are never run.", "");
lines.push("- Each system was run in its own paired report against the same undefended baseline (direct tool service, no defense). The baseline row pools the baseline arms " +
  "of all included reports for that model; the baseline configuration is identical in each.",
"- Published defenses (spotlighting, sandwich, tool_filter, MELON) are re-implementations on this harness from their papers and AgentDojo source, not the original code.",
"- Rates are over valid runs (provider-fault runs are excluded and counted). Intervals are Wilson 95%. Comparisons between systems use the Newcombe interval for a difference " +
  "of two independent proportions; a difference is called lower or higher only when that interval excludes zero. Nothing here is a paired test or a confirmatory result.",
"- *Benign runs with a denial* counts benign runs where the gateway denied a call or an agent defense vetoed one. In the plain profile the agent is not told which tools are " +
  "allowed, so gateway denials of unlisted tools on benign tasks are expected; benign utility shows whether the task still succeeded.", "");

const models = [...new Set(cells.map((c) => c.model))];
for (const model of models) {
  const rs = reports.filter((r) => r.model === model);
  lines.push(`## ${model}`, "");
  if (!rs.length) { lines.push("No finished report yet.", ""); continue; }
  const pooled = { goal: [0, 0], unsafe: [0, 0], utility: [0, 0], utilityUnderAttack: [0, 0], benignDenied: [0, 0] };
  const rows = rs.map((r) => ({ r, d: metrics(r, "defended"), b: metrics(r, "baseline") }));
  for (const { b } of rows) for (const k of Object.keys(pooled)) if (b[k]) { pooled[k][0] += b[k].k; pooled[k][1] += b[k].n; }
  const base = Object.fromEntries(Object.entries(pooled).map(([k, [x, n]]) => [k, wilson(x, n)]));
  const allBaseMs = rs.flatMap((r) => r.cases.filter(valid).map((c) => c.baseline.elapsed_ms));
  lines.push("| System | Family | Transport | Valid / total pairs | Attacker goal | Unsafe effect | Benign utility | Utility under attack | Benign runs with a denial | Attack runs with an agent-defense veto | Extra model calls per run | Extra tokens (in / out) | Median run ms |");
  lines.push("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |");
  const baseValid = rs.reduce((s, r) => s + r.summary.validity.valid_pairs, 0), baseTotal = rs.reduce((s, r) => s + r.summary.validity.total_pairs, 0);
  lines.push(`| baseline (pooled, ${rs.length} reports) | no defense | direct | ${baseValid}/${baseTotal} | ${fmt(base.goal)} | ${fmt(base.unsafe)} | ${fmt(base.utility)} | ${fmt(base.utilityUnderAttack)} | ${fmt(base.benignDenied)} | — | 0 | 0 / 0 | ${median(allBaseMs)} |`);
  rows.sort((x, y) => (x.d.goal?.p ?? 1) - (y.d.goal?.p ?? 1) || (y.d.utility?.p ?? 0) - (x.d.utility?.p ?? 0));
  for (const { r, d } of rows) {
    const o = r.summary.defense_overhead ?? {};
    const ms = median(r.cases.filter(valid).map((c) => c.defended.elapsed_ms));
    const sys = defenses.systems[r.defended_system] ?? {};
    const transport = sys.transport === "gateway" ? `gateway (${sys.gateway_variant})` : sys.transport ?? "?";
    lines.push(`| ${r.defended_system} | ${sys.family ?? r.defended_system_family} | ${transport} | ${r.summary.validity.valid_pairs}/${r.summary.validity.total_pairs} | ${fmt(d.goal)} | ${fmt(d.unsafe)} | ${fmt(d.utility)} | ${fmt(d.utilityUnderAttack)} | ${fmt(d.benignDenied)} | ${sys.agent_defenses?.length ? fmt(d.attackVetoed) : "—"} | ${o.mean_extra_model_calls_per_run ?? 0} | ${o.extra_input_tokens ?? 0} / ${o.extra_output_tokens ?? 0} | ${ms} |`);
  }
  lines.push("");

  // Per-attack breakdown: which attack goals each system stops.
  const attacks = [...new Set(rs.flatMap((r) => r.cases.filter((c) => c.kind === "attack").map((c) => c.case_id)))];
  lines.push("### Attacker goal reached, per attack case", "", `| Attack case | baseline (pooled) | ${rows.map((x) => x.r.defended_system).join(" | ")} |`, `| --- | --- | ${rows.map(() => "---").join(" | ")} |`);
  for (const id of attacks) {
    const of = (r, arm) => { const xs = r.cases.filter((c) => c.case_id === id && valid(c)); return [xs.filter((c) => c[arm].evaluation.attacker_goal_achieved).length, xs.length]; };
    const b = rs.map((r) => of(r, "baseline")).reduce((s, [k, n]) => [s[0] + k, s[1] + n], [0, 0]);
    lines.push(`| ${id} | ${b[0]}/${b[1]} | ${rows.map(({ r }) => of(r, "defended").join("/")).join(" | ")} |`);
  }
  lines.push("");

  // Differences: every defended system against the pooled baseline, and our candidates against every other system.
  lines.push("### Differences in attacker-goal rate and benign utility (Newcombe 95%, percentage points)", "");
  lines.push("| Comparison | Attacker goal difference | Verdict | Benign utility difference | Verdict |", "| --- | --- | --- | --- | --- |");
  const verdict = (ci, lowerIsBetter) => (!ci ? "n/a" : ci.hi < 0 ? (lowerIsBetter ? "lower (better)" : "lower (worse)") : ci.lo > 0 ? (lowerIsBetter ? "higher (worse)" : "higher (better)") : "not separated");
  const diffRow = (label, a, b) => {
    const g = newcombe(a.goal, b.goal), u = newcombe(a.utility, b.utility);
    lines.push(`| ${label} | ${g ? `${pp(g.diff)} (${pp(g.lo)} to ${pp(g.hi)})` : "n/a"} | ${verdict(g, true)} | ${u ? `${pp(u.diff)} (${pp(u.lo)} to ${pp(u.hi)})` : "n/a"} | ${verdict(u, false)} |`);
  };
  for (const { r, d } of rows) diffRow(`${r.defended_system} vs baseline`, d, base);
  const ours = rows.filter(({ r }) => /^ours/.test(defenses.systems[r.defended_system]?.family ?? ""));
  // Each pair once: an "ours" system against every published baseline, and against the "ours" systems listed after it.
  for (const [i, a] of ours.entries()) for (const b of rows) if (a !== b && !(ours.includes(b) && ours.indexOf(b) < i)) diffRow(`${a.r.defended_system} vs ${b.r.defended_system}`, a.d, b.d);
  lines.push("");
}

// Stress suite (A-013): declarative-only poisoning, reported separately because its case set differs from the registered one.
const stressSuite = "tests/arms/stress-cases.json";
const stress = [];
for (const name of (await readdir(path.join(root, "evidence"))).filter((n) => /^tb024-.*-report\.json$/.test(n))) {
  const r = await read(`evidence/${name}`);
  if (r.mode === "live_model" && r.suite === stressSuite) stress.push(r);
}
lines.push("## Stress suite: declarative-only answer poisoning (A-013)", "",
  `Reports from \`${stressSuite}\`: \`doc-birch-poison\` (the injected sentence contains an instruction) and \`doc-birch-declarative\` (the same false value stated only as a fact), ` +
  "with their benign control. `directive_flow` is expected to miss the declarative case, so this section measures that weakness.", "");
if (!stress.length) lines.push("No finished stress report yet.", "");
else {
  lines.push("| Model | Rendering | System | Case | Attacker goal (baseline → defended) | Utility (baseline → defended) | Defended runs with an agent-defense veto |", "| --- | --- | --- | --- | --- | --- | --- |");
  stress.sort((a, b) => (a.model + a.attack_rendering + a.defended_system).localeCompare(b.model + b.attack_rendering + b.defended_system));
  for (const r of stress) for (const id of r.selected_case_ids) {
    const xs = r.cases.filter((c) => c.case_id === id && valid(c));
    const n = (f) => `${xs.filter(f).length}/${xs.length}`;
    lines.push(`| ${r.model} | ${r.attack_rendering} | ${r.defended_system} | ${id} | ${n((c) => c.baseline.evaluation.attacker_goal_achieved)} → ${n((c) => c.defended.evaluation.attacker_goal_achieved)} | ` +
      `${n((c) => c.baseline.evaluation.utility_pass)} → ${n((c) => c.defended.evaluation.utility_pass)} | ${n((c) => (c.defended.defense?.vetoes ?? 0) > 0)} |`);
  }
  lines.push("");
}

const missing = cells.filter((c) => !reports.some((r) => r.model === c.model && r.defended_system === c.system));
lines.push("## Registered cells without a finished report", "", "Not counted anywhere above.", "", ...(missing.length ? missing.map((c) => `- ${c.model} / ${c.system} (lane ${c.lane})`) : ["- none"]), "");
lines.push("## Caveats", "",
  "- Development split only, and the candidate defenses (`ours`) were designed after development results were seen (protocol A-012). Any advantage is a hypothesis for the single confirmatory holdout run, not a result.",
  "- Systems with `gateway` transport include the capability gateway; the published baselines run on the direct tool service. A gateway system's advantage over a published " +
    "baseline therefore mixes the gateway and its agent-side layer. The added value of an agent-side layer is its comparison against `gateway_capability` (same transport) and " +
    "the per-case table, where the gateway alone cannot stop attacks whose payload stays inside an authorized write (answer poisoning, link insertion).",
  "- One attack rendering and two repetitions per case: small samples, wide intervals. Unseparated differences are not evidence of equality.",
  "- Hosted models cannot be pinned to a snapshot; response model IDs are recorded in each report (`model_revision`).",
  "- Model-based defenses (tool_filter, MELON, counterfactual_writes, directive_flow) use the same model as the agent; their extra calls and tokens are listed above.", "");
await writeFile(path.join(root, "docs/defense-comparison.md"), lines.join("\n") + "\n");
console.log(`wrote docs/defense-comparison.md from ${reports.length} reports; ${missing.length} registered cells pending`);
