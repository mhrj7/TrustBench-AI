// Generates docs/pilot-results-tb024.md from the live-run evidence files. No number is typed by hand.
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "evidence");
const reports = [];
for (const name of (await readdir(dir)).filter((n) => /^tb024-.*-report\.json$/.test(n))) {
  const r = JSON.parse(await readFile(path.join(dir, name), "utf8"));
  if (r.mode === "live_model" && r.summary?.validity) reports.push({ name, ...r });
}
const cell = (x) => (x.denominator === 0 ? "n/a" : `${x.numerator}/${x.denominator}` + (x.rate !== null ? ` (${(x.rate * 100).toFixed(0)}%)` : ""));
// Attack runs whose only unsafe effect was using a tool outside the task allowlist (the injection goal was not reached).
const unlistedOnly = (r, arm) => {
  const rows = r.cases.filter((c) => c.kind === "attack" && !c.baseline.invalid && !c.defended.invalid);
  const k = rows.filter((c) => { const e = c[arm].evaluation; return !e.security_pass && !e.attacker_goal_achieved && e.prohibited_side_effects.length > 0 && e.prohibited_side_effects.every((x) => x.startsWith("security.executed_unlisted_tool")); }).length;
  return `${k}/${rows.length}`;
};
const pair = (o, key) => `${cell(o[key].baseline)} → ${cell(o[key].defended)}`;
const order = (a, b) => (a.prompt_profile + a.model + a.attack_rendering).localeCompare(b.prompt_profile + b.model + b.attack_rendering);
reports.sort(order);

const lines = [];
lines.push("# TB-024 pilot results on the development split (not confirmatory)", "");
lines.push("Generated by `scripts/summarize-live-results.mjs` from `evidence/tb024-*-report.json`. Every number below is read from those files.", "");
lines.push("Notation: `baseline → defended`. Rates are numerator/denominator over valid (case × repetition) pairs; `n/a` means the cell was not run. " +
  "Runs where the model node failed with a provider fault are invalid, excluded from every rate and counted in the `invalid` column. " +
  "'exposed' means the injected text appeared in a model-visible message; 'goal|exposed' is the attacker-goal rate among exposed runs only. " +
  "Intervals are in the JSON files; no paired test is claimed. Holdout fixtures are never run.", "");
for (const profile of [...new Set(reports.map((r) => r.prompt_profile))]) {
  lines.push(`## Prompt profile: ${profile}`, "");
  lines.push("| Model | Attack text | Reps | Invalid pairs | Made a tool call | Exposed to injection | Attacker goal | Goal given exposed | Unsafe effect | …of which unlisted-tool use only | Benign utility | Utility under attack | Benign calls blocked |");
  lines.push("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |");
  for (const r of reports.filter((x) => x.prompt_profile === profile)) {
    const s = r.summary;
    lines.push(`| ${r.model} | ${r.attack_rendering} | ${r.repetitions} | ${s.validity.invalid_pairs}/${s.validity.total_pairs} | ${pair(s, "engagement_made_a_tool_call")} | ${pair(s, "injection_exposure")} | ${pair(s, "attacker_goal_achieved")} | ${pair(s, "attacker_goal_achieved_among_exposed")} | ${pair(s, "unsafe_committed_effect")} | ${unlistedOnly(r, "baseline")} → ${unlistedOnly(r, "defended")} | ${s.benign_utility_pass.baseline.denominator ? pair(s, "benign_utility_pass") : "n/a"} | ${pair(s, "utility_under_attack")} | ${cell(s.false_block_calls_on_benign)} |`);
  }
  lines.push("");
}
const matrix = JSON.parse(await readFile(path.join(root, "configs/live-matrix.yaml"), "utf8"));
const have = new Set(reports.map((r) => `${r.model}|${r.prompt_profile}|${r.attack_rendering}`));
const missing = [];
for (const model of Object.values(matrix.lanes).flat()) for (const profile of matrix.prompt_profiles) for (const rendering of matrix.renderings) {
  if (rendering.profiles && !rendering.profiles.includes(profile)) continue;
  if (!have.has(`${model}|${profile}|${rendering.id}`)) missing.push(`${model} / ${profile} / ${rendering.id}`);
}
lines.push("## Registered matrix cells without results", "", "These cells are in `configs/live-matrix.yaml` but have no finished report (not run, interrupted, or blocked by provider quota). They are not counted anywhere above.", "", ...(missing.length ? missing.map((m) => `- ${m}`) : ["- none"]), "");
lines.push("## How to read this", "",
  "- `trusted_user_control` is the positive control: the forbidden goal is requested in the trusted user message instead of an injected document. " +
  "A high baseline attacker-goal rate there shows the harness and model can produce the outcome, so a low rate for injected text reflects the model resisting the injection, not a broken run.",
  "- The `hardened` profile adds explicit trust and authorization rules to the shared prompt; the `plain` profile does not. Both arms always share the same profile.",
  "- 'Unsafe effect' also counts executing a tool outside the task allowlist; without the allowlist in the prompt (plain profile) models often do, and the gateway blocks it. The attacker-goal columns are the injection-specific measure.",
  "- 'Benign calls blocked' is denied calls over all benign-task calls in the defended arm. It is high in the plain profile because the agent is not told which tools are allowed; the model recovers after a denial, so benign utility is reported separately.",
  "- Exposure matters: if the model never read the injected text (exposed 0/N), the attacker-goal rate says nothing about resistance.",
  "- Differences of a few runs are noise at these sample sizes.", "");
await writeFile(path.join(root, "docs/pilot-results-tb024.md"), lines.join("\n") + "\n");
console.log(`wrote docs/pilot-results-tb024.md from ${reports.length} live reports`);
