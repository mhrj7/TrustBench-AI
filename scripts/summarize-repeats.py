#!/usr/bin/env python3
"""TB-028: evaluate every live report with repeated runs and generate docs/repeated-runs.md. No number is typed by hand.

Each report is evaluated on its own (one model, rendering, profile and system), because combining reports would merge
different conditions into one cluster. Reports executed from a fixed schedule are checked against it."""
import json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from src.evaluation.repeats import evaluate, load_runs  # noqa: E402

MIN_REPS = 3
out_dir = ROOT / 'evidence/tb028'
out_dir.mkdir(parents=True, exist_ok=True)
rows = []
for path in sorted((ROOT / 'evidence').glob('tb024-*-report.json')):
    rep = json.loads(path.read_text())
    if rep.get('mode') != 'live_model' or rep.get('repetitions', 0) < MIN_REPS:
        continue
    schedule = json.loads((ROOT / rep['schedule']['file']).read_text()) if rep.get('schedule') else None
    result = evaluate(load_runs([rep]), schedule)
    result['report'] = str(path.relative_to(ROOT))
    (out_dir / path.name.replace('-report.json', '-repeats.json')).write_text(json.dumps(result, indent=1, sort_keys=True) + '\n')
    rows.append((rep, result))

fmt = lambda v: '—' if v is None else f'{v:.2f}'
ci = lambda c: '' if not c else f' [{c[0]:.2f}, {c[1]:.2f}]'
lines = ['# Repeated-run results (TB-028)', '',
         'Generated by `scripts/summarize-repeats.py` with `src/evaluation/repeats.py` from every live report with at least '
         f'{MIN_REPS} repetitions; per-report evaluations are in `evidence/tb028/`. A cluster is one (task, attack variant); its repeats '
         'are correlated, so each cluster is summarized first and clusters are averaged. Brackets are 95% cluster-bootstrap intervals '
         '(registry resamples and seed). *All repeats* is the share of clusters that succeeded in every valid repeat; *any repeat* in at '
         'least one. The pooled per-run rate is shown only for contrast and is not used for inference. ICC is the intra-cluster '
         'correlation of outcomes. Invalid (provider-fault) repeats are excluded and counted. Development split only.', '']
for metric, title in (('benign', 'Benign task success'), ('attack_goal', 'Attacker goal NOT reached (attack runs)'), ('attack_security', 'No unsafe effect (attack runs)')):
    lines += [f'## {title}', '', '| Model | Suite | Rendering | Profile | System | Schedule | Arm | Clusters | Valid / invalid repeats | Mean success frequency | All repeats | Any repeat | Pooled (contrast) | ICC | Clusters with mixed outcomes | Paired difference (defended − baseline) |',
              '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |']
    for rep, result in sorted(rows, key=lambda x: (x[0]['model'], x[0].get('suite') or '', x[0]['attack_rendering'], x[0]['prompt_profile'], x[0].get('defended_system') or x[0].get('defended_variant') or '')):
        for system, s in result['systems'].items():
            m = s['metrics'][metric]
            if not m['clusters']:
                continue
            sched = 'yes' if rep.get('schedule') else 'no'
            for arm in ('baseline', 'defended'):
                a = m['arms'][arm]
                pd = m['paired_difference'] if arm == 'defended' else None
                diff = '' if not pd or pd['mean_frequency_difference'] is None else f"{pd['mean_frequency_difference']:+.2f}{ci(pd['ci95_cluster_bootstrap'])}"
                lines.append(f"| {rep['model']} | {Path(rep.get('suite') or 'tests/arms/smoke-cases.json').stem} | {rep['attack_rendering']} | {rep['prompt_profile']} | {system} | {sched} | {arm} | {a['clusters_with_valid_repeats']} | {a['valid_repeats']} / {a['invalid_repeats_excluded']} | "
                             f"{fmt(a['mean_success_frequency'])}{ci(a['mean_success_frequency_ci95'])} | {fmt(a['all_repeats_success_rate'])}{ci(a['all_repeats_success_ci95'])} | {fmt(a['any_repeat_success_rate'])} | "
                             f"{fmt(a['pooled_run_rate_not_for_inference'])} | {fmt(a['intra_cluster_correlation'])} | {a['clusters_with_mixed_outcomes']} | {diff} |")
    lines.append('')
sched_rows = [(r, res) for r, res in rows if r.get('schedule')]
lines += ['## Schedule integrity', '', 'Reports executed from a fixed task-seed schedule, checked unit by unit against it.', '']
lines += [f"- `{r['schedule']['file']}` (content {r['schedule']['content_sha256'][:12]}, order {r['schedule']['order_sha256'][:12]}): "
          + '; '.join(f"{sys_}: {v['integrity']['units_observed']}/{v['integrity']['units_expected']} units, missing {len(v['integrity']['missing_units'])}, unscheduled {len(v['integrity']['unscheduled_units'])}" for sys_, v in res['systems'].items())
          for r, res in sched_rows] or ['- none yet']
lines += ['', 'Order invariance is tested end to end in `evidence/tb028-order-invariance-report.json` (same units executed in two orders give identical pairing, denominators and results).', '']
(ROOT / 'docs/repeated-runs.md').write_text('\n'.join(lines) + '\n')
print(f'evaluated {len(rows)} repeated-run reports; wrote docs/repeated-runs.md')
