"""TB-045: the label audit is reproducible, blind, fully adjudicated, and its re-analysis relabels the full population."""
import json, runpy, shutil, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCRIPT = ROOT / 'scripts/label-audit.py'
NS = runpy.run_path(str(SCRIPT), run_name='label_audit')
CFG, OUT = NS['CFG'], NS['OUT']


def test_the_sample_and_blind_packets_are_reproduced_from_the_seed(tmp_path):
    for k in ('packets', 'sample'):
        NS['sample'].__globals__['OUT'][k] = tmp_path / OUT[k].name
    try:
        NS['sample']()
    finally:
        NS['sample'].__globals__['OUT'].update({k: ROOT / v for k, v in CFG['outputs'].items()})
    assert (tmp_path / 'packets.jsonl').read_text() == OUT['packets'].read_text()
    assert json.loads((tmp_path / 'sample.json').read_text()) == json.loads(OUT['sample'].read_text())


def test_packets_never_show_the_evaluator_verdicts_arm_or_stratum():
    for line in OUT['packets'].read_text().splitlines():
        p = json.loads(line)
        assert set(p) <= {'packet_id', 'workflow', 'kind', 'task_contract', 'expected_outcome', 'trajectory', 'attack'}
        text = json.dumps(p)
        for leak in ('security_pass', 'utility_pass', 'attacker_goal_achieved', 'prohibited_side_effects', 'reason_codes', '"arm"', 'baseline', 'defended'):
            assert leak not in text, (p['packet_id'], leak)


def test_two_reviewers_labelled_every_packet():
    ids = {json.loads(l)['packet_id'] for l in OUT['packets'].read_text().splitlines()}
    for k in ('review_a', 'review_b'):
        rows = NS['load'](OUT[k])
        assert set(rows) == ids
        assert all(all(isinstance(r[lab], bool) for lab in CFG['labels']) for r in rows.values())


def test_every_trace_reconstruction_agrees_with_the_registered_label_where_the_rule_was_not_defective():
    # A-029 relabels from the trace; on runs the defect did not touch (goal registered false), the trace must also find no
    # attacker content, or the reconstruction would not be a faithful stand-in for the state-based evaluator.
    fixed, changed = NS['corrected_reports'](apply_a029=True)
    registered, _ = NS['corrected_reports'](apply_a029=False)
    flips = 0
    for record in fixed:
        for (x, new), (_, old) in zip(fixed[record], registered[record]):
            for cn, co in zip(new['cases'], old['cases']):
                for arm in ('baseline', 'defended'):
                    a, b = cn[arm]['evaluation'], co[arm]['evaluation']
                    if a['attacker_goal_achieved'] != b['attacker_goal_achieved']:
                        assert b['attacker_goal_achieved'] and not a['attacker_goal_achieved'] and not a['security_pass']
                        flips += 1
    assert flips == len(changed) == len(json.loads((OUT['sample'].parent / 'rerun.json').read_text())['a029_relabelled_runs'])


def test_committed_report_is_reproduced_from_the_audit_files(tmp_path):
    saved = {k: tmp_path / k for k in ('csv', 'doc', 'json')}
    for k, dst in saved.items():
        shutil.copy(OUT[k], dst)
    try:
        subprocess.run([sys.executable, str(SCRIPT), 'report'], cwd=ROOT, check=True, capture_output=True)  # exits non-zero on an unadjudicated disagreement
        strip = lambda t: [l for l in t.splitlines() if not l.startswith('Generated by')]
        assert strip(OUT['doc'].read_text()) == strip(saved['doc'].read_text()), 'research/label-audit.md is out of date: run scripts/label-audit.py report'
        assert OUT['csv'].read_text() == saved['csv'].read_text()
    finally:
        for k, src in saved.items():
            shutil.copy(src, OUT[k])
