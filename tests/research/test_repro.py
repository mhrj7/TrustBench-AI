"""TB-046: the reproducibility package is complete, excludes secrets and restricted data, and detects real differences."""
import json, re, runpy, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCRIPT = ROOT / 'scripts/repro.py'
NS = runpy.run_path(str(SCRIPT), run_name='repro')
CFG = NS['CFG']


def test_the_published_tree_passes_the_exclusion_secret_and_hash_check():
    p = subprocess.run([sys.executable, str(SCRIPT), 'check'], cwd=ROOT, capture_output=True, text=True)
    assert p.returncode == 0, p.stdout


def test_the_readme_is_generated_from_the_manifest_and_last_log():
    m = json.loads((ROOT / 'repro/manifest.json').read_text())
    assert (ROOT / 'repro/README.md').read_text() == NS['readme'](m), 'run scripts/repro.py build'


def test_every_split_publishes_its_fixture_ids_and_the_seeds_match_the_registry():
    m = json.loads((ROOT / 'repro/manifest.json').read_text())
    splits = json.loads((ROOT / 'data/splits.json').read_text())
    assert sorted(m['fixtures']['by_split']['holdout']) == sorted(splits['holdout_manifest']['fixture_ids'])
    assert sorted(m['fixtures']['by_split']['holdout2']) == sorted(splits['holdout2_manifest']['fixture_ids'])
    reg = json.loads((ROOT / 'protocol/experiment-registry.yaml').read_text())
    assert m['seeds']['pair_order_seed'] == reg['pair_order_seed'] and m['seeds']['holdout.split_seed'] == reg['holdout']['split_seed']


def test_the_secret_patterns_catch_real_key_shapes_and_not_prose():
    rx = [re.compile(p) for p in CFG['secret_patterns']]
    for key in ['nvapi-' + 'A1b2C3d4E5f6G7h8I9j0K1l2', 'AIza' + 'Sy' + 'x' * 33, 'gsk_' + 'a' * 24, 'hf_' + 'b' * 24, '-----BEGIN ' + 'RSA PRIVATE KEY-----']:
        assert any(r.search(key) for r in rx), key
    assert not any(r.search('set NVIDIA_API_KEY in .env; keys look like nvapi-...') for r in rx)


def test_only_declared_volatile_fields_may_differ():
    strip = NS['strip']
    a = json.dumps({'generated_at': '2026-10-17T00:00:00+00:00', 'rate': 0.5, 'cases': [{'request_id': 'x', 'pass': True}]})
    b = json.dumps({'generated_at': '2026-10-18T09:09:09+00:00', 'rate': 0.5, 'cases': [{'request_id': 'y', 'pass': True}]})
    assert strip('r.json', a) == strip('r.json', b)
    assert strip('r.json', a) != strip('r.json', b.replace('0.5', '0.51'))
    md = 'Generated by `scripts/label-audit.py report` on {}; ...\n| x | 1 |'
    assert strip('a.md', md.format('2026-10-17')) == strip('a.md', md.format('2026-10-18'))
    assert strip('a.md', md.format('2026-10-17')) != strip('a.md', md.format('2026-10-17').replace('| 1 |', '| 2 |'))


def test_the_last_recorded_reproduction_passed_at_a_committed_commit():
    log = json.loads((ROOT / CFG['reproduction_log']).read_text())
    assert log['outcome'] == 'REPRODUCED' and not log['unexpected_changes']
    assert len(log['steps']) == len(CFG['offline_steps']) and all(s['exit_code'] == 0 for s in log['steps'])
    assert subprocess.run(['git', 'cat-file', '-e', log['commit'] + '^{commit}'], cwd=ROOT).returncode == 0
